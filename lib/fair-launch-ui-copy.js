export function fairLaunchUiText(locale, key, variables = {}) {
  const language = String(locale || "en").toLowerCase().split("-")[0];
  const catalog = language === "es" ? es : en;
  const template = catalog[key] || en[key] || key;
  return Object.entries(variables).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

